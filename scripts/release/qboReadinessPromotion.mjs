// Deterministic promotion of the reviewed candidate into the canonical atomic envelope.
// No network, database, transaction submission or hosted journal mutation.
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { lexSql, parseAtomicEnvelope } from '../ci/atomicEnvelope.mjs';

export const CANDIDATE = 'release/candidates/qbo-readiness-r2/20261214100000_qbo_readiness_controls.sql';
export const SOURCE = '20261214100000_qbo_readiness_controls.sql';
export const CANDIDATE_SHA256 = '00cb216ee96596fb1bb81a27e652d8ef701ac0b175bca25ca3bda206da1cca7f';
const significant = sql => lexSql(sql).filter(t => !['ws','comment'].includes(t.type));
export function candidateStatements(bytes) {
  if (bytes.length !== 17890 || crypto.createHash('sha256').update(bytes).digest('hex') !== CANDIDATE_SHA256) throw new Error('QBO candidate fingerprint mismatch');
  const sql = bytes.toString('utf8');
  const tokens = significant(sql);
  if (tokens[0]?.text !== 'BEGIN' || tokens[1]?.text !== ';' || tokens.at(-2)?.text !== 'COMMIT' || tokens.at(-1)?.text !== ';') throw new Error('QBO candidate transaction boundaries changed');
  const body = sql.slice(tokens[1].end, tokens.at(-2).start);
  const statements = []; let start = 0;
  for (const token of lexSql(body)) {
    if (token.type === 'punct' && token.text === ';') {
      statements.push(body.slice(start, token.start).trim()); start = token.end;
    }
  }
  if (significant(body.slice(start)).length || statements.some(s => !significant(s).length)) throw new Error('QBO candidate statement boundary refused');
  return statements;
}
export function renderPromotion(bytes) {
  const statements = candidateStatements(bytes);
  const label = 'qbo_readiness';
  const segments = statements.map((sql, i) => {
    const suffix = [Math.floor(i/676),Math.floor(i/26)%26,i%26].map(n => String.fromCharCode(97+n)).join('');
    return `  EXECUTE $m${label}${suffix}$\n${sql}\n$m${label}${suffix}$;`;
  });
  const rendered = `-- GENERATED by scripts/release/qboReadinessPromotion.mjs; do not edit.\n-- Candidate SHA-256 ${CANDIDATE_SHA256} (17890 bytes), merged at 8d00f99.\n-- Every non-transaction statement preserved verbatim; atomicity belongs to this ONE DO statement.\nDO $cfoclose_${label}$\nBEGIN\n${segments.join('\n')}\nEND\n$cfoclose_${label}$;\n`;
  const parsed = parseAtomicEnvelope(rendered);
  if (JSON.stringify(parsed.statements) !== JSON.stringify(statements)) throw new Error('QBO promotion statement drift');
  return rendered;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (!['--write','--check'].includes(mode)) throw new Error('usage: qboReadinessPromotion.mjs --write | --check');
  const rendered = renderPromotion(fs.readFileSync(CANDIDATE));
  const target = `supabase/migrations/${SOURCE}`;
  if (mode === '--write') fs.writeFileSync(target, rendered);
  if (!fs.readFileSync(target).equals(Buffer.from(rendered))) throw new Error('QBO authored migration drift');
  console.log(`QBO promotion verified: ${Buffer.byteLength(rendered)} bytes; candidate unchanged`);
}
