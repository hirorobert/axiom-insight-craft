import { describe, expect, it } from "vitest";
import * as XLSX from "xlsx";
import { readTrialBalanceSource, type XlsxLike } from "../../../supabase/functions/_shared/tbSource";
import { PRINTED_FOOTER_RULES, footerRuleFor, isStandalonePageNumber } from "../../../supabase/functions/_shared/printedReportMetadata";

// Phase 1 §3.1: printed-report footers are recognised only with positional and structural evidence, through one
// configurable rule set. Every identity and amount here is invented.
const HEADER = ["NATURAL ACCOUNT", "DESCRIPTION", "DEBIT AMOUNT", "CREDIT AMOUNT"];
const ACCOUNTS = [["91001", "Service charges", 100.12, null], ["91002", "Rent received", 46.25, null], ["93001", "Capital", null, 146.37]];
const CONTROL = [null, null, 146.37, 146.37];

function read(rows: unknown[][]) {
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(rows), "TB");
  const bytes = new Uint8Array(XLSX.write(wb, { type: "array", bookType: "xls" }));
  return readTrialBalanceSource(bytes, { fileName: "synthetic.xls", periodYear: 2026, currency: "TZS" }, XLSX as unknown as XlsxLike);
}
const printed = (footer: unknown[][], body: unknown[][] = ACCOUNTS) =>
  read([["SYNTHETIC TRADERS LTD"], ["Trial balance for the year ended 30 June 2026"], [], HEADER, ...body, CONTROL, [], ...footer]);
const reasonOf = (r: ReturnType<typeof read>, row: number) => r.lineage.find((l) => l.rowNumber === row)?.reason ?? null;

describe("printed-report footer rule set (text only)", () => {
  it.each([
    ["Page 1 of 3", "page_number"], ["page 12", "page_number"], ["Pg. 2/9", "page_number"], ["- 4 -", "page_marker"],
    ["Printed on 15/10/2026 09:12", "print_date"], ["Run date: 2026-10-15", "print_date"], ["Report date", "print_date"],
    ["*** End of report ***", "end_of_report"], ["END OF LISTING", "end_of_report"],
    ["Prepared by:", "signature_line"], ["Approved by ____", "signature_line"], ["Signature", "signature_line"],
    ["Date:", "date_line"], ["Date: 15/10/2026", "date_line"], ["__________", "rule_line"],
    ["Report generated by Synthetic Ledger", "generated_by"],
  ])("recognises %j as %s", (text, id) => expect(footerRuleFor(text)?.id).toBe(id));
  it.each(["Date palm plantation", "Page builders ltd", "Printing and stationery", "Prepaid rent", "Run-off reserve", "Signature loans receivable"])(
    "does not treat the account-like text %j as a footer", (text) => expect(footerRuleFor(text)).toBeNull());
  it("is one exported, configurable list and names no source system", () => {
    expect(PRINTED_FOOTER_RULES.length).toBeGreaterThan(0);
    expect(JSON.stringify(PRINTED_FOOTER_RULES.map((r) => r.pattern.source)).toLowerCase()).not.toMatch(/mfumo|serikali/);
  });
  it("a standalone page number is a small whole number only", () => {
    expect(isStandalonePageNumber(3)).toBe(true);
    expect(isStandalonePageNumber("12")).toBe(true);
    expect(isStandalonePageNumber(146.37)).toBe(false);
    expect(isStandalonePageNumber(0)).toBe(false);
    expect(isStandalonePageNumber(123456)).toBe(false);
  });
});

describe("printed-report footers in a file (position and structure)", () => {
  it("a clean printed workbook with every footer variant: all rows accounted for, no issues, control total checked", () => {
    const r = printed([["Prepared by:"], ["Date:"], ["__________"], ["Printed on 15/10/2026"], ["Page 1 of 1"], ["*** End of report ***"], [null, null, null, null, 1]]);
    expect(r.issues).toEqual([]);
    expect(r.accounts.map((a) => a.accountCode)).toEqual(["91001", "91002", "93001"]);
    expect(r.lineage.filter((l) => l.disposition === "total")).toHaveLength(1);
    const s = r.lineageSummary;
    expect(s.preamble + s.header + s.blank + s.heading + s.total + s.zero_balance + s.account + s.rejected).toBe(s.rowsRead);
    expect(r.lineage.filter((l) => /^Printed report footer/.test(l.reason ?? ""))).toHaveLength(7);
  });
  it("a standalone page number after the accounts is a footer only because of its position and structure", () => {
    const r = printed([[null, null, null, null, 2]]);
    expect(r.issues).toEqual([]);
    expect(reasonOf(r, 10)).toBe("Printed report footer: Page number");
  });
  it("a genuine account with footer-like wording survives, wherever it sits", () => {
    const body = [...ACCOUNTS.slice(0, 2), ["40020", "Date palm plantation", null, 10], ["40021", "Prepared by contractors", 10, null], ACCOUNTS[2]];
    const r = read([["SYNTHETIC TRADERS LTD"], [], HEADER, ...body, [null, null, 156.37, 156.37], [], ["Prepared by:"]]);
    expect(r.accounts.map((a) => a.accountName)).toEqual(["Service charges", "Rent received", "Date palm plantation", "Prepared by contractors", "Capital"]);
    expect(r.issues).toEqual([]);
  });
  it("footer-like text with an amount is never discarded: it is processed as a row and refused", () => {
    const r = printed([["Page 2", null, 5, null]]);
    expect(r.issues.map((i) => i.code)).toContain("MISSING_ACCOUNT_CODE");
    expect(r.lineage.filter((l) => l.disposition === "total")).toHaveLength(0);
  });
  it("text after the accounts that no rule recognises is kept and held for review, never dropped", () => {
    const r = printed([["Synthetic Ledger System v4 — internal"]]);
    expect(r.issues.map((i) => [i.code, i.severity])).toEqual([["UNRECOGNISED_TRAILING_TEXT", "review"]]);
    expect(r.blocking).toBe(false);
    expect(r.lineage.find((l) => l.rowNumber === 10)?.disposition).toBe("heading");
    expect(r.lineage.filter((l) => l.disposition === "total")).toHaveLength(1);
  });
  it("a footer phrase between accounts gives no footer treatment and changes no amounts", () => {
    const body = [ACCOUNTS[0], ["Page 1 of 2"], ACCOUNTS[1], ACCOUNTS[2]];
    const r = read([["SYNTHETIC TRADERS LTD"], [], HEADER, ...body, CONTROL]);
    expect(r.accounts).toHaveLength(3);
    expect(r.totals).toEqual({ debitMinor: 14637n, creditMinor: 14637n, differenceMinor: 0n });
    expect(r.lineage.filter((l) => /^Printed report footer/.test(l.reason ?? ""))).toHaveLength(0);
  });
  it("an unlabelled numeric row between accounts is still blocking, not a total", () => {
    const body = [ACCOUNTS[0], [null, null, 100.12, 0], ACCOUNTS[1], ACCOUNTS[2]];
    const r = read([["SYNTHETIC TRADERS LTD"], [], HEADER, ...body, CONTROL]);
    expect(r.issues.map((i) => i.code)).toContain("MISSING_ACCOUNT_CODE");
    expect(r.blocking).toBe(true);
  });
});
