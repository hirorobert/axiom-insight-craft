import { describe, expect, it } from 'vitest';
import * as XLSX from 'xlsx';
import { readTrialBalanceSource, type XlsxLike } from '../../../supabase/functions/_shared/tbSource';

// Entirely invented amounts and identities; no client workbook is a test dependency.
function printedWorkbook(credit = 146.37, printedCredit = credit, currency = 'TZS', midFile = false) {
  const rows: unknown[][] = [
    ['SYNTHETIC ENTITY'], ['Trial balance for the year ended 30 June 2026'], [],
    ['NATURAL ACCOUNT', null, null, 'DESCRIPTION', null, null, null, 'DEBIT AMOUNT', null, null, null, null, 'CREDIT AMOUNT'],
    [null, null, null, null, null, null, null, currency, null, null, null, null, currency],
    ['91001', null, null, 'Service charges', null, null, null, 100.12],
    ...(midFile ? [[null, null, null, null, null, null, null, 100.12, null, null, null, null, 0]] : []),
    ['91002', null, null, 'Service charges', null, null, null, 46.25],
    ['93001', null, null, 'Capital', null, null, null, null, null, null, null, null, credit],
    [null, null, null, null, null, null, null, 146.37, null, null, null, null, printedCredit],
    [], ['Prepared by:'], ['Date:'], [], ['Report generated by synthetic engine', null, null, null, null, null, null, null, null, null, null, null, null, 1],
  ];
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(rows), 'TB');
  const bytes = new Uint8Array(XLSX.write(wb, { type: 'array', bookType: 'xls' }));
  return readTrialBalanceSource(bytes, { fileName: 'synthetic.xls', periodYear: 2026, currency: 'TZS' }, XLSX as unknown as XlsxLike);
}

describe('printed binary XLS: metadata, identities and control totals', () => {
  it('recognises natural account codes, currency labels and a matching terminal control total', () => {
    const r = printedWorkbook();
    expect(r.issues).toEqual([]);
    expect(r.accounts.map(a => a.accountCode)).toEqual(['91001', '91002', '93001']);
    expect(r.totals).toEqual({ debitMinor: 14637n, creditMinor: 14637n, differenceMinor: 0n });
    expect(r.lineage.filter(l => l.disposition === 'total')).toHaveLength(1);
  });
  it('reports genuine imbalance rather than currency-label or duplicate-description errors', () => {
    const r = printedWorkbook(140.02);
    expect(r.issues.map(i => i.code)).toEqual(['TRIAL_BALANCE_IMBALANCE']);
    expect(r.totals?.differenceMinor).toBe(635n);
  });
  it('separates printed control mismatch from balanced account arithmetic', () => {
    const r = printedWorkbook(146.37, 145.37);
    expect(r.issues.map(i => i.code)).toEqual(['TOTAL_ROW_MISMATCH']);
    expect(r.totals?.differenceMinor).toBe(0n);
  });
  it('reports both independent defects when accounts and printed controls disagree', () => {
    expect(printedWorkbook(140.02, 139.02).issues.map(i => i.code)).toEqual(['TOTAL_ROW_MISMATCH', 'TRIAL_BALANCE_IMBALANCE']);
  });
  it('refuses a currency label that contradicts selected context', () => {
    expect(printedWorkbook(146.37, 146.37, 'USD').issues.map(i => i.code)).toContain('CURRENCY_MISMATCH');
  });
  it('does not discard an unlabelled numeric row between accounts as a total', () => {
    expect(printedWorkbook(146.37, 146.37, 'TZS', true).issues.map(i => i.code)).toContain('MISSING_ACCOUNT_CODE');
  });
});
