// canonicalStatement/serialization.ts — deterministic serialization and
// identifier hashing.
//
// `sha256Hex` is a small, self-contained, synchronous SHA-256
// implementation (pure TypeScript, no dependency). It is deliberately
// synchronous rather than using the platform's async WebCrypto
// (`crypto.subtle.digest`, used elsewhere in this codebase for source-byte
// hashing) because finding/evaluation identity is computed inline inside
// the rule engine's otherwise-synchronous evaluate/runRule path — making
// that async would force every caller (including every test) onto a
// Promise chain for no benefit, since identity hashing here operates on
// short, already-in-memory canonical strings, not large file bytes. It is
// verified against the standard SHA-256 test vectors in serialization.test.ts.

/** Recursively sorts object keys and renders bigint exactly, so two structurally-equal values always serialize identically regardless of key insertion order. */
export function canonicalStringify(value: unknown): string {
  return JSON.stringify(canonicalize(value));
}

function canonicalize(value: unknown): unknown {
  if (typeof value === "bigint") {
    return { __bigint__: value.toString() };
  }
  if (Array.isArray(value)) {
    return value.map(canonicalize);
  }
  if (value !== null && typeof value === "object") {
    const sortedKeys = Object.keys(value as Record<string, unknown>).sort();
    const result: Record<string, unknown> = {};
    for (const key of sortedKeys) {
      result[key] = canonicalize((value as Record<string, unknown>)[key]);
    }
    return result;
  }
  return value;
}

