  IF v_new IS NOT NULL THEN PERFORM public._portfolio_bump(v_new); END IF;
  IF v_old IS NOT NULL AND v_old IS DISTINCT FROM v_new THEN PERFORM public._portfolio_bump(v_old); END IF;
  RETURN NULL;
END;
$$;
